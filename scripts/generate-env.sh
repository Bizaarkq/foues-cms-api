#!/usr/bin/env bash
# Generates the .env consumed by docker-compose.yml with random secrets.
# Usage: ./scripts/generate-env.sh [--force]
set -euo pipefail

cd "$(dirname "$0")/.."

if [[ -f .env && "${1:-}" != "--force" ]]; then
  echo "ERROR: .env already exists — pass --force to overwrite it." >&2
  exit 1
fi

rand() { openssl rand -base64 "$1" | tr -d '\n'; }

# DB credentials are tied to the MySQL volume — preserve them on --force
# so that an existing database is not locked out after regeneration.
existing_db_root=""
existing_db_name=""
existing_db_user=""
existing_db_pass=""
if [[ -f .env ]]; then
  existing_db_root=$(grep -E '^DB_ROOT_PASSWORD=' .env | cut -d= -f2- || true)
  existing_db_name=$(grep -E '^DB_NAME=' .env | cut -d= -f2- || true)
  existing_db_user=$(grep -E '^DB_USER=' .env | cut -d= -f2- || true)
  existing_db_pass=$(grep -E '^DB_PASSWORD=' .env | cut -d= -f2- || true)
fi

DB_ROOT_PASSWORD="${existing_db_root:-$(rand 24)}"
DB_NAME="${existing_db_name:-foues}"
DB_USER="${existing_db_user:-foues}"
DB_PASSWORD="${existing_db_pass:-$(rand 24)}"

cat > .env <<EOF
# Generated by scripts/generate-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)

# --- Build mode: development (test servers, merges override) | production ---
BUILD_ENV=development

# --- MySQL ---
DB_ROOT_PASSWORD=${DB_ROOT_PASSWORD}
DB_NAME=${DB_NAME}
DB_USER=${DB_USER}
DB_PASSWORD=${DB_PASSWORD}

# --- Strapi secrets ---
STRAPI_APP_KEYS=$(rand 16),$(rand 16),$(rand 16),$(rand 16)
STRAPI_API_TOKEN_SALT=$(rand 16)
STRAPI_ADMIN_JWT_SECRET=$(rand 16)
STRAPI_TRANSFER_TOKEN_SALT=$(rand 16)
STRAPI_ENCRYPTION_KEY=$(rand 32)
STRAPI_JWT_SECRET=$(rand 16)

# --- Frontend ---
# Internal URL (server-to-server inside Docker — do NOT change).
STRAPI_URL=http://cms:1337
# Public URL the browser uses to load media (images, PDFs).
# In local dev: http://localhost:8000  |  On server: http://<server-ip>:8000
STRAPI_PUBLIC_URL=http://localhost:8000
# Fill these once the API is up, by running:
#   docker compose run --rm foues-cms-api node scripts/create-api-tokens.js
STRAPI_API_TOKEN=
FORM_SUBMIT_TOKEN=
MAGAZINE_TRACK_TOKEN=

# --- NextAuth ---
# Set AUTH_URL / NEXTAUTH_URL to the public URL of the frontend (e.g. http://<server-ip>:3000).
AUTH_SECRET=$(rand 32)
AUTH_URL=http://localhost:3000
NEXTAUTH_URL=http://localhost:3000
GOOGLE_CLIENT_ID=dummy
GOOGLE_CLIENT_SECRET=dummy

# --- Cache revalidation ---
REVALIDATE_SECRET=$(rand 32)

# --- Frontend extras ---
# URL del Campus Virtual mostrada en el navbar (opcional; vacía = link oculto)
CAMPUS_VIRTUAL_URL=
EOF

echo ".env generated."
echo "Next: start the stack, then create the API tokens:"
echo "  docker compose -f docker-compose.yml run --rm foues-cms-api node scripts/create-api-tokens.js"
